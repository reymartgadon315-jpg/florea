    isLocal() {
        return window.location.hostname === 'localhost' || window.location.hostname === '127.0.0.1';
    },

    apiOrigin() {
        return window.location.hostname === 'florea.onrender.com'
            ? 'https://florea-api.onrender.com'
            : window.location.origin;
    },

    apiUrl(path) {
        return new URL(path, `${this.apiOrigin()}/`).href;
    },

    resolveImageUrl(path) {
        return typeof path === 'string' && /^\/api\/product-images\/[0-9a-f-]{36}$/i.test(path)
            ? this.apiUrl(path)
            : path;
    },

    fetchApi(path, options = {}) {
        const apiOrigin = this.apiOrigin();
        return fetch(this.apiUrl(path), {
            ...options,
            credentials: apiOrigin === window.location.origin ? 'same-origin' : 'include'
        });
    },

    async request(path, options = {}) {
        const response = await this.fetchApi(path, {
            ...options,
            headers: {
                'content-type': 'application/json',
                ...options.headers
            }
        });
        const result = response.status === 204 ? null : await response.json();
        if (!response.ok) {
            const error = new Error(result && result.error ? result.error : `Order service returned ${response.status}.`);
            error.status = response.status;
            error.code = result && result.code;
            throw error;
        }
        return result;
    },

    escapeText(value) {
        return String(value).replace(/[&<>"']/g, character => ({
            '&': '&amp;',
            '<': '&lt;',
            '>': '&gt;',
            '"': '&quot;',
            "'": '&#39;'
        })[character]);
    },

    renderOrderItems(order, imageSize = '42px') {
        const details = Array.isArray(order.itemDetails) && order.itemDetails.length
            ? order.itemDetails
            : (Array.isArray(order.items) ? order.items : []).map(name => ({ name }));

        return details.map(item => {
            const data = item && typeof item === 'object' ? item : {};
            const name = typeof item === 'string' ? item : data.name;
            const productName = name.replace(/\s*×\d+\s*$/, '');
            const catalogProduct = window.FloreaProducts
                ? Object.values(window.FloreaProducts).flat().find(product => product.n === productName)
                : null;
            const legacyProductName = productName
                .replace(/\s*\([^)]*\)\s*$/, '')
                .replace(/^(?:Iced|Hot)\s+/, '');
            const imageIsAsset = typeof data.image === 'string' &&
                data.image.startsWith('assets/') && !data.image.split('/').includes('..');
            const imageIsUploaded = typeof data.image === 'string' &&
                /^\/api\/product-images\/[0-9a-f-]{36}$/i.test(data.image);
            const imageIsLocal = typeof data.image === 'string' &&
                /^data:image\/(?:jpeg|png|webp);base64,[A-Za-z0-9+/]+={0,2}$/i.test(data.image);
            const image = imageIsAsset || imageIsUploaded || imageIsLocal
                ? this.resolveImageUrl(data.image)
                : this.resolveImageUrl(
                    (catalogProduct && catalogProduct.image) ||
                    this.productImages[productName] ||
                    this.productImages[legacyProductName] ||
                    ''
                );
            const quantity = data.quantity ? ` ×${data.quantity}` : '';
            const options = [];
            if (data.drinkSize) {
                options.push(`${data.drinkSize}${data.drinkTemperature ? ` · ${data.drinkTemperature}` : ''}`);
            }
            if (data.wrapStyle) options.push(`Wrap: ${data.wrapStyle}`);
            if (data.messageCard) options.push(`Card: “${data.messageCard}”`);

            return `
                <div class="cashier-order-item">
                    ${image
                        ? `<img class="cashier-order-item__image" src="${this.escapeText(image)}" alt="${this.escapeText(name || 'Ordered item')}" loading="lazy" decoding="async" style="width:${imageSize};height:${imageSize};">`
                        : `<span class="cashier-order-item__placeholder" style="width:${imageSize};height:${imageSize};" aria-hidden="true">${this.escapeText(data.emoji || '🛍️')}</span>`}
                    <div class="cashier-order-item__copy">
                        <div class="cashier-order-item__name">${this.escapeText(name || 'Menu item')}${quantity}</div>
                        ${options.length ? `<div class="cashier-order-item__options">${options.map(option => this.escapeText(option)).join(' · ')}</div>` : ''}
                    </div>
                </div>
            `;
        }).join('');
    }
